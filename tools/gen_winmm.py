# Generates src/winmm_stubs.S and src/winmm_names.h from the mingw winmm.def.
# Each export jumps through a pointer filled from the real System32 winmm.dll at load.
import sys, re
defp = sys.argv[1]
names = []
for line in open(defp):
    line = line.strip()
    if not line or line.startswith(';') or line.startswith('LIBRARY') or line == 'EXPORTS':
        continue
    n = re.split(r'[\s@=]', line)[0]
    if n and n not in names:
        names.append(n)
with open('src/winmm_names.h', 'w') as f:
    f.write('/* generated by tools/gen_winmm.py */\n#define WINMM_COUNT %d\nstatic const char *const winmm_names[WINMM_COUNT] = {\n' % len(names))
    for n in names:
        f.write('  "%s",\n' % n)
    f.write('};\n')
with open('src/winmm_stubs.S', 'w') as f:
    f.write('/* generated by tools/gen_winmm.py */\n.text\n')
    for i, n in enumerate(names):
        f.write('.globl %s\n%s:\n  jmp *winmm_ptrs+%d(%%rip)\n' % (n, n, i * 8))
    f.write('.section .drectve\n')
    for n in names:
        f.write('.ascii " -export:%s"\n' % n)
print(len(names), 'exports')
